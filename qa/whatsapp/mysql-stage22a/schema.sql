-- Etapa 2.2-A: definición consolidada para una base de prueba NUEVA.
-- Aplicación únicamente por el lanzador aislado. No es una migración de DimaBug.
-- IDs/counters BIGINT firmados compatibles con Java Long; reloj operativo UTC.
CREATE TABLE wa_conversacion (
 id BIGINT NOT NULL AUTO_INCREMENT,
 clave_hmac BINARY(32) NOT NULL,
 estado VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'LIBRE',
 revision_estado BIGINT NOT NULL DEFAULT 0,
 secuencia_recibida BIGINT NOT NULL DEFAULT 0,
 referencia CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 estado_cifrado MEDIUMBLOB NULL,
 destino_cifrado BLOB NULL,
 propuesta_expira DATETIME(6) NULL,
 ultima_imagen_evento BIGINT NULL COMMENT 'Referencia lógica: limpiar antes de purgar el evento; sin FK circular',
 ultima_imagen_emitida DATETIME(6) NULL,
 reserva_token CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 reserva_hasta DATETIME(6) NULL,
 cercado BIGINT NOT NULL DEFAULT 0,
 ventana_ingreso DATETIME(6) NULL,
 ingresados INT NOT NULL DEFAULT 0,
 creado_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 actualizado_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 retener_hasta DATETIME(6) NOT NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uq_wa_conversacion_clave(clave_hmac),
 KEY ix_wa_conversacion_reserva(reserva_hasta,id),
 KEY ix_wa_conversacion_expira(propuesta_expira,id),
 KEY ix_wa_conversacion_retencion(retener_hasta,id),
 CONSTRAINT ck_wa_conversacion_estado CHECK(estado IN ('LIBRE','ESPERA_OCR','ESPERA_CONFIRMACION','CERRADA','EXPIRADA')),
 CONSTRAINT ck_wa_conversacion_contadores CHECK(revision_estado>=0 AND secuencia_recibida>=0 AND cercado>=0 AND ingresados>=0),
 CONSTRAINT ck_wa_conversacion_reserva CHECK((reserva_token IS NULL AND reserva_hasta IS NULL) OR (reserva_token IS NOT NULL AND reserva_hasta IS NOT NULL)),
 CONSTRAINT ck_wa_conversacion_propuesta CHECK(
   (estado='ESPERA_CONFIRMACION' AND referencia IS NOT NULL AND propuesta_expira IS NOT NULL AND estado_cifrado IS NOT NULL)
   OR (estado<>'ESPERA_CONFIRMACION' AND referencia IS NULL AND propuesta_expira IS NULL)),
 CONSTRAINT ck_wa_conversacion_retencion CHECK(retener_hasta>=creado_en)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin;

CREATE TABLE wa_evento (
 id BIGINT NOT NULL AUTO_INCREMENT,
 clave_hmac BINARY(32) NOT NULL,
 contenido_hmac BINARY(32) NOT NULL,
 conversacion_id BIGINT NULL,
 secuencia BIGINT NULL,
 tipo VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 estado VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'PENDIENTE',
 esquema INT NOT NULL DEFAULT 1,
 contenido_cifrado MEDIUMBLOB NULL,
 emitido_en DATETIME(6) NULL,
 recibido_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 actualizado_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 terminado_en DATETIME(6) NULL,
 vence_en DATETIME(6) NOT NULL,
 retener_hasta DATETIME(6) NOT NULL,
 intentos INT NOT NULL DEFAULT 0,
 proximo_intento DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 reserva_token CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 reserva_hasta DATETIME(6) NULL,
 cercado BIGINT NOT NULL DEFAULT 0,
 ultimo_error_codigo VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
 resultado_codigo VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uq_wa_evento_clave(clave_hmac),
 UNIQUE KEY uq_wa_evento_secuencia(conversacion_id,secuencia),
 UNIQUE KEY uq_wa_evento_id_conversacion(id,conversacion_id),
 KEY ix_wa_evento_pendiente(estado,proximo_intento,id),
 KEY ix_wa_evento_reserva(estado,reserva_hasta,id),
 KEY ix_wa_evento_retencion(retener_hasta,id),
 CONSTRAINT fk_wa_evento_conversacion FOREIGN KEY(conversacion_id) REFERENCES wa_conversacion(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT ck_wa_evento_tipo CHECK(tipo IN ('TEXTO','IMAGEN','ESTADO','DESCONOCIDO')),
 CONSTRAINT ck_wa_evento_estado CHECK(estado IN ('PENDIENTE','EN_PROCESO','REINTENTO','TERMINADO','ERROR_PERMANENTE','EXPIRADO','IGNORADO','SUPERADO')),
 CONSTRAINT ck_wa_evento_secuencia CHECK((conversacion_id IS NULL AND secuencia IS NULL) OR (conversacion_id IS NOT NULL AND secuencia IS NOT NULL AND secuencia>0)),
 CONSTRAINT ck_wa_evento_mensaje CHECK(tipo NOT IN ('TEXTO','IMAGEN') OR (conversacion_id IS NOT NULL AND secuencia IS NOT NULL)),
 CONSTRAINT ck_wa_evento_contadores CHECK(intentos>=0 AND cercado>=0 AND esquema>=1),
 CONSTRAINT ck_wa_evento_reserva CHECK(
  (estado='EN_PROCESO' AND reserva_token IS NOT NULL AND reserva_hasta IS NOT NULL)
  OR (estado<>'EN_PROCESO' AND reserva_token IS NULL AND reserva_hasta IS NULL)),
 CONSTRAINT ck_wa_evento_retencion CHECK(vence_en>=recibido_en AND retener_hasta>=vence_en)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin;

CREATE TABLE wa_respuesta (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 evento_id BIGINT NOT NULL,
 conversacion_id BIGINT NOT NULL,
 estado VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'PENDIENTE',
 revision_objetivo BIGINT NULL,
 plan_cifrado MEDIUMBLOB NULL,
 preparado_cifrado MEDIUMBLOB NULL,
 intentos_preparacion INT NOT NULL DEFAULT 0,
 intentos_envio INT NOT NULL DEFAULT 0,
 fase_reintento VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NULL,
 proximo_intento DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 reserva_token CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 reserva_hasta DATETIME(6) NULL,
 cercado BIGINT NOT NULL DEFAULT 0,
 proveedor_clave_hmac BINARY(32) NULL,
 estado_entrega VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NULL,
 ultimo_error_codigo VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
 creado_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 actualizado_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 vence_en DATETIME(6) NOT NULL,
 retener_hasta DATETIME(6) NOT NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uq_wa_respuesta_evento(evento_id),
 UNIQUE KEY uq_wa_respuesta_proveedor(proveedor_clave_hmac),
 KEY ix_wa_respuesta_evento_conversacion(evento_id,conversacion_id),
 KEY ix_wa_respuesta_conversacion(conversacion_id),
 KEY ix_wa_respuesta_pendiente(estado,proximo_intento,id),
 KEY ix_wa_respuesta_reserva(estado,reserva_hasta,id),
 KEY ix_wa_respuesta_retencion(retener_hasta,id),
 CONSTRAINT fk_wa_respuesta_evento_conversacion FOREIGN KEY(evento_id,conversacion_id) REFERENCES wa_evento(id,conversacion_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_wa_respuesta_conversacion FOREIGN KEY(conversacion_id) REFERENCES wa_conversacion(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT ck_wa_respuesta_estado CHECK(estado IN ('PENDIENTE','PREPARANDO','PREPARADA','ENVIANDO','ACEPTADA','SIMULADA','REINTENTO','INCIERTA','ERROR_PERMANENTE','EXPIRADA','CANCELADA')),
 CONSTRAINT ck_wa_respuesta_contadores CHECK(intentos_preparacion>=0 AND intentos_envio>=0 AND cercado>=0 AND (revision_objetivo IS NULL OR revision_objetivo>=0)),
 CONSTRAINT ck_wa_respuesta_entrega CHECK(estado_entrega IS NULL OR estado_entrega IN ('ENVIADA','ENTREGADA','LEIDA','FALLIDA')),
 CONSTRAINT ck_wa_respuesta_reserva CHECK(
  (estado IN ('PREPARANDO','ENVIANDO') AND reserva_token IS NOT NULL AND reserva_hasta IS NOT NULL)
  OR (estado NOT IN ('PREPARANDO','ENVIANDO') AND reserva_token IS NULL AND reserva_hasta IS NULL)),
 CONSTRAINT ck_wa_respuesta_reintento CHECK(
  (estado='REINTENTO' AND fase_reintento IS NOT NULL AND fase_reintento IN ('PREPARACION','ENVIO'))
  OR (estado<>'REINTENTO' AND fase_reintento IS NULL)),
 CONSTRAINT ck_wa_respuesta_plan CHECK(estado NOT IN ('PENDIENTE','PREPARANDO','PREPARADA','ENVIANDO','REINTENTO') OR plan_cifrado IS NOT NULL),
 CONSTRAINT ck_wa_respuesta_preparada CHECK(estado NOT IN ('PREPARADA','ENVIANDO') OR preparado_cifrado IS NOT NULL),
 CONSTRAINT ck_wa_respuesta_aceptada CHECK(estado<>'ACEPTADA' OR proveedor_clave_hmac IS NOT NULL),
 CONSTRAINT ck_wa_respuesta_retencion CHECK(vence_en>=creado_en AND retener_hasta>=vence_en)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin;
